`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////
//  acq_to_bram.v  ——  四通道打包 + 乒乓写控制 + 与 PS 握手
//
//  【这个模块干什么】
//    把四个麦克风"同一时刻"的采样拼成一个 64 位字，写进 BRAM；
//    写满一帧就记一笔账告诉 PS；PS 读完再记一笔账回来说明可以让位了。
//
//  ─────────────────────── 用"两个抽屉"理解它 ───────────────────────
//    面前有两个抽屉，每个抽屉有 1024 个格子。
//      · 每来一个采样点，就往当前抽屉的当前格子里塞一份，手指往右挪一格；
//      · 塞满 1024 格 → 记一笔账（wr_cnt + 1）→ 换另一个抽屉继续塞；
//      · 只要至少有一个抽屉是空的，你就一直塞、一刻不停；
//      · 两个抽屉都还没被助手（PS）清空过，你就只能干等。
//    PS 那边看你的账本：发现「你装的箱数 ≠ 我读的箱数」就去读掉，
//    读完整理完立刻把自己的账本数字 +1 —— 注意是"读完就记账"，
//    不是"算完方位才记账"（否则计算时间会被算进采集周期里，白白拖慢采集）。
//
//  ─────────────────────── 为什么只用两个状态 ───────────────────────
//    FILL：正在灌当前这一箱
//    WAIT：这一箱满了，看看有没有空箱，有就回去 FILL
//    整个控制逻辑就这么两步，没有第三种情况。
//
//  ─────────────────── 为什么握手要用两个计数器而不是一个标志位 ───────────────────
//    如果只用一个标志位，它就必然要"PL 置位、PS 清零" —— 两个不同时钟域、
//    两个不同方向去写同一个位，谁赢是不确定的，轻则丢事件、重则状态卡死。
//    改成两个单向的账本：
//      · PL 维护 wr_cnt：「我一共装满几箱」
//      · PS 维护 rd_cnt：「我一共读完几箱」
//    两边各写各的，物理上永不冲突。PL 只需要把 rd_cnt 同步进来做一次比较。
//
//  ─────────────────────── 数据在这里长什么样 ───────────────────────
//    一个 64 位字 = { CH3[15:0], CH2[15:0], CH1[15:0], CH0[15:0] }
//    四个通道"同一时刻"的采样落在同一个地址里，
//    所以 PS 读一次地址就能拿到四路严格对齐的数据 —— 这是算 TDOA 的前提。
//    每个通道只保留 24 位里的高 16 位（s[23:8]），理由见顶层的说明。
//
//  ─────────────────────── 改帧长时要同时改四处 ───────────────────────
//    ① 本模块和顶层的 FRAME 参数   ② BRAM 的 Depth（= 2 × FRAME）
//    ③ PS 侧的循环次数             ④ FFT 的点数
//    漏掉任何一处都不会报错，只会让数据莫名其妙 —— 这类错误最难查。
//////////////////////////////////////////////////////////////////////////////
module acq_to_bram #(
    parameter integer FRAME = 1024   // 一帧的采样点数，必须是 2 的幂
)(
    input  wire        clk,          // 50 MHz 系统时钟
    input  wire        rst_n,        // 低电平复位
    // ---- 四路麦克风数据（四路必然同一拍有效）----
    input  wire [23:0] ch0,
    input  wire [23:0] ch1,
    input  wire [23:0] ch2,
    input  wire [23:0] ch3,
    input  wire        sample_vld,   // 四路同时收满 24 位的那一拍，高 1 拍
    // ---- 与 PS 的握手（接 AXI GPIO）----
    input  wire [1:0]  rd_cnt_ps,    // PS 的账本：读完几箱了
    output wire [1:0]  wr_cnt_ps,    // 我的账本：装满几箱了
    // ---- BRAM Port B（本模块只写，不读）----
    output reg         bram_we,      // 写使能
    output reg  [10:0] bram_addr,    // 字地址：1 位箱号 + 10 位格号
    output reg  [63:0] bram_din      // 要写进去的一个 64 位字
);

    // 帧内地址位宽：FRAME=1024 时算出 10 位（地址 0~1023）
    localparam integer    IDXW     = $clog2(FRAME);
    localparam [IDXW-1:0] LAST_IDX = FRAME - 1;   // 最后一格的格号

    //======================================================================
    // ① 跨时钟域：把 PS 的账本同步进来（打两拍）
    //    rd_cnt_ps 来自 PS 的 FCLK 时钟域，本模块跑在 50 MHz 晶振域，
    //    两者是真异步（两个独立时钟源，相位会缓慢漂移）。
    //    直接拿去比较会碰到亚稳态，必须先过两级触发器再用。
    //======================================================================
    reg [1:0] rd_s0 = 2'd0, rd_s1 = 2'd0;

    always @(posedge clk) begin
        rd_s0 <= rd_cnt_ps;
        rd_s1 <= rd_s0;          // ★ 只有 rd_s1 可以拿去做逻辑比较
    end

    //======================================================================
    // ② 指针与账本
    //======================================================================
    reg  [1:0]      wr_cnt = 2'd0;       // 我一共装满几箱（每满一箱 +1）
    reg  [IDXW-1:0] idx    = {IDXW{1'b0}};   // 当前这一箱里，写到第几格了
    wire            bank = wr_cnt[0];    // 当前该用哪个箱：0 还是 1

    // 有几箱写好了、但 PS 还没读走：可能是 0 / 1 / 2
    // 用 2 位减法，天然按模 4 回绕，正好匹配 wr_cnt 的 2 位宽度。
    wire [1:0] unread = wr_cnt - rd_s1;

    // 还有空箱吗？
    //   unread = 0 → 两箱都空（刚上电）
    //   unread = 1 → 一箱待 PS 读，另一箱空着   → 可以继续写
    //   unread = 2 → 两箱都待 PS 读             → 必须停下来等
    wire has_slot = (unread < 2'd2);

    //======================================================================
    // ③ 打包：四个 16 位拼成一个 64 位字
    //    取每个通道 24 位中的高 16 位（[23:8]）。
    //    INMP441 信噪比只有 61 dB，24 位里真正携带信息的约 10 位；
    //    16 位相当于 96 dB 动态范围，远超麦克风本身的能力 → 零信息损失。
    //    好处很直接：BRAM 占用减少一半。
    //======================================================================
    wire [63:0] packed = {ch3[23:8], ch2[23:8], ch1[23:8], ch0[23:8]};

    //======================================================================
    // ④ 主状态机：只有两个状态
    //======================================================================
    localparam FILL = 1'b0,      // 正在灌这一箱
               WAIT = 1'b1;      // 这一箱满了，去找空箱

    reg state;

    always @(posedge clk) begin
        if (!rst_n) begin
            state     <= FILL;
            wr_cnt    <= 2'd0;
            idx       <= {IDXW{1'b0}};
            bram_we   <= 1'b0;
            bram_addr <= 11'd0;
            bram_din  <= 64'd0;
        end
        else begin
            // 默认不写。
            // 这一点非常重要：BRAM 的写使能必须是"只在真正有数据的那一拍拉高"，
            // 否则 50 MHz 的每一拍都会往同一个地址重复写，把数据冲掉。
            bram_we <= 1'b0;

            case (state)

            //--------------------------------------------------------------
            // FILL：每来一个有效采样点，写一次 BRAM，格号 +1
            //--------------------------------------------------------------
            FILL: begin
                if (sample_vld) begin
                    bram_addr <= {bank, idx};    // 地址 = 箱号 + 格号
                    bram_din  <= packed;         // 四路拼好的 64 位
                    bram_we   <= 1'b1;           // ★ 只写这一拍

                    if (idx == LAST_IDX) begin
                        // 这一箱的最后一格，本箱满了
                        wr_cnt <= wr_cnt + 2'd1;     // 记账：我又装满一箱
                        idx    <= {IDXW{1'b0}};      // 格号归零
                        state  <= WAIT;              // 去看看有没有空箱
                    end
                    else begin
                        idx <= idx + 1'b1;           // 手指往右挪一格
                    end
                end
            end

            //--------------------------------------------------------------
            // WAIT：本箱已满。有空箱就继续灌，没有就待着
            //--------------------------------------------------------------
            WAIT: begin
                if (has_slot) state <= FILL;
                // 没有空箱 → 状态保持不变，这段时间进来的采样点会被丢弃。
                // 这就是"等 PS"的代价。用乒乓（两个箱）时正常不会走到这里，
                // 只有 PS 处理太慢（超过一帧时间）才会。
            end

            default: state <= FILL;

            endcase
        end
    end

    // 把账本送出去（接 AXI GPIO 的输入通道，PS 从那里读）
    assign wr_cnt_ps = wr_cnt;

endmodule
