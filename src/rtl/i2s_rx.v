`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////
//  i2s_rx.v  ——  INMP441 数字麦克风 I2S 接收（单路）
//
//  【这个模块干什么】
//    麦克风把声音变成一串二进制位，从 SD 线上一位一位地吐出来。
//    本模块负责按正确的节拍，把 24 个 bit 一位不差地收进来，
//    拼成一个 24 位采样值，并在收齐的那一拍给出 vld 脉冲。
//
//  【INMP441 的 I2S 时序】（24 bit，标准 Philips 格式）
//    · WS 每 64 个 SCK 翻转一次，用来区分左右声道；
//    · WS 翻转后的第 1 个 SCK 周期是无效位（MSB 会延迟 1 位）；
//    · 第 2 ~ 25 个 SCK 周期才是 24 位有效数据，MSB 先出、LSB 最后；
//    · 数据在 SCK 下降沿更新，接收方在 SCK 上升沿附近采样。
//    → 所以本模块在 bit_idx = 1..24 期间取数，
//      并且让 bit_idx=1 取到的位落到 24 位数据的最高位（bit23）。
//
//  【为什么完全不用跨时钟域处理】
//    SCK 和 WS 不是从外面接进来的，而是由顶层 cnt 计数器分频出来的，
//    与系统时钟 50MHz 同源、相位锁死 —— 属于"同一个时钟域"。
//    （判据是"有没有固定的相位关系"，不是"频率是否相同"。）
//    所以 SCK / WS / SD 全都在 50MHz 域里，不需要异步 FIFO，也不需要打两拍。
//
//  【cnt 编码】（顶层 50MHz 下自由运行的 10 位计数器，0~1023 循环）
//    cnt[3:0] = 0..15    一个 SCK 周期内的 16 个相位（cnt[3] 本身就是 SCK）
//    cnt[8:4] = 0..31    一个声道内的第几个 SCK 周期（也就是 bit_idx）
//    cnt[9]   = 0 / 1    声道标志（0 = 左声道，1 = 右声道）
//    四个麦克风共用同一个 cnt，所以它们在同一拍照做同一件事 → 天然同步。
//
//  【采样点为什么选在 cnt[3:0]==7】
//    SCK 的上升沿发生在 cnt[3:0] 由 7 变 8 的那一刻。
//    数据在 SCK 下降沿（cnt[3:0] 由 15 变 0）之后更新。
//    在 cnt[3:0]==7 采样，意味着：
//      · 距上一次数据更新已经过去 7 拍 = 140 ns  → 建立时间余量充足
//      · 距下一次数据更新还有 9 拍 = 180 ns      → 保持时间余量充足
//    两个方向都有大半个半周期的余量，落在数据最稳定的窗口正中间。
//////////////////////////////////////////////////////////////////////////////
module i2s_rx (
    input  wire        clk,      // 系统时钟 50 MHz
    input  wire        rst_n,    // 低电平复位
    input  wire [9:0]  cnt,      // 顶层共享的 I2S 位计数器
    input  wire        sd,       // 本路麦克风的 SD 数据线
    output reg  [23:0] sample,   // 收齐的 24 位采样（二进制补码，有符号）
    output reg         vld       // 收满 24 位的那一拍拉高 1 拍
);

    //------------------------------------------------------------------------
    // 从 cnt 里解出三个时间信息
    //------------------------------------------------------------------------
    wire       sample_point = (cnt[3:0] == 4'd7);   // 采样时刻：SCK 上升沿前 1 拍
    wire       left_ch      = (cnt[9]   == 1'b0);   // L/R 接 GND 时，数据在左声道
    wire [4:0] bit_idx      = cnt[8:4];             // 本声道内第几个 SCK 周期

    //------------------------------------------------------------------------
    // 移位收数
    //   bit_idx = 1 → 收到的是 MSB，最后会停在 bit23
    //   bit_idx = 24 → 收到的是 LSB，同时说明 24 位已收齐
    //------------------------------------------------------------------------
    reg [23:0] shift;      // 正在拼装的移位寄存器

    always @(posedge clk) begin
        if (!rst_n) begin
            shift  <= 24'd0;
            sample <= 24'd0;
            vld    <= 1'b0;
        end
        else begin
            // vld 是脉冲：默认拉低，只有收满的那一刻拉高一拍
            vld <= 1'b0;

            if (sample_point && left_ch) begin
                if (bit_idx >= 5'd1 && bit_idx <= 5'd24) begin
                    // 每来一位就往左移一格，新位补到最低位。
                    // 先收到的 MSB 会随着 24 次移位最终停在 bit23。
                    shift <= {shift[22:0], sd};

                    if (bit_idx == 5'd24) begin
                        // 最后一位到齐：一次性把完整的 24 位锁存出去，
                        // 同时给出 vld。注意 sample 和 vld 是同一拍更新，
                        // 所以外面看到 vld=1 的时候，sample 已经是完整值了。
                        sample <= {shift[22:0], sd};
                        vld    <= 1'b1;
                    end
                end
            end
        end
    end

endmodule
