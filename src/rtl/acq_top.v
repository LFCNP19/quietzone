`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////
//  acq_top.v  ——  声源定位装置  PL 侧顶层
//  开发板：黑金 AX7020（XC7Z020-CLG400-2）
//
//  ══════════════════════════ 整体数据流 ══════════════════════════
//
//      50 MHz 晶振 (U18)
//          │
//          └─→ 分频计数器 cnt（10 位，0~1023 自由循环）
//                 ├─ cnt[3] = SCK，3.125 MHz  ──→ 4 个麦克风共用
//                 ├─ cnt[9] = WS， 48.83 kHz  ──→ 4 个麦克风共用
//                 └─ 整个 cnt 送给 4 个 i2s_rx 当节拍
//
//      4 × INMP441 ──SD0..SD3──→ 4 × i2s_rx ──→ s0~s3 (24bit) + vld
//                                                    │
//                                              acq_to_bram
//                                    （打包 64 位 / 乒乓写 / 与 PS 握手）
//                                                    │
//                                            BRAM Port B
//                                                    │
//                                        （PS 从 AXI 那一侧读走 → 算方位 → 串口）
//
//  ═══════════════════ 为什么采样率是 48.83 kHz 而不是整 48 kHz ═══════════════════
//      SCK = 50 MHz ÷ 16   = 3.125 MHz
//      WS  = 50 MHz ÷ 1024 = 48.828 kHz
//    分频比被 50 MHz 锁死了，凑不出整 48 kHz。
//    但对 TDOA 测向来说，四路"严格同步"比"采样率是个整数"重要得多；
//    48.83 kHz 是个稳定不变的值，算法侧按这个数算时延即可，完全没有影响。
//    （顺便：INMP441 要求 SCK 在 0.5~3.2 MHz、WS 在 7.8~50 kHz，
//      3.125 MHz / 48.83 kHz 都落在范围内。）
//
//  ═══════════════════ 四路为什么天然同步（TDOA 的前提）═══════════════════
//    4 个 i2s_rx 吃的是同一个 clk、同一个 cnt，
//    它们会在完全相同的那一拍收满各自的 24 位，
//    所以 s0~s3 就是"同一时刻"的四个采样，相位误差为 0。
//    这四个 vld 用"与"合起来的道理也一样：任何一路都不掉队。
//
//  ═══════════════════ 为什么采集 24 位却只存 16 位 ═══════════════════
//    · 采集必须按协议收满 24 位（I2S 协议本身固定 24 位，移位寄存器躲不掉）；
//    · 但存的时候只取每个通道的高 16 位 sample[23:8]。
//    依据：INMP441 的 SNR = 61 dB(A)，
//         等效有效位数 ENOB ≈ (61 − 1.76) / 6.02 ≈ 9.8 位，
//         也就是说 24 位里真正有信息的只有约 10 位。
//         16 位 = 96 dB 动态范围，远超麦克风自身 61 dB 的能力 → 零信息损失。
//    换来的好处：BRAM 占用直接减半。
//    ⚠️ 记住这个结论：本项目里位宽不是精度瓶颈，麦克风的信噪比才是。
//
//  ═══════════════ BRAM 地址与位宽（PS 侧写代码必须用到）═══════════════
//    数据宽度 64 位 = 4 通道 × 16 位，四路同一时刻的数据落在一个地址里。
//
//      PL 侧 Port B  按「字」寻址：地址 0 ~ 2047，共 2048 个 64 位字
//      PS 侧 AXI     按「字节」寻址：0x0000 ~ 0x3FFF，共 16 KB
//      换算关系：字节地址 = 字地址 × 8   （64 位 = 8 字节）
//
//      区 0：字地址 0     起始 → PS 侧 0x0000（偏移 0）
//      区 1：字地址 1024  起始 → PS 侧 0x2000（偏移 8192）
//
//    PS 侧建议的读法（用 u32 指针，不要用 u64 强转）：
//
//      volatile u32 *p = (volatile u32 *)(0x40000000 + bank * 8192);
//      u32 lo = p[2 * i];        // = { ch1[15:0], ch0[15:0] }
//      u32 hi = p[2 * i + 1];    // = { ch3[15:0], ch2[15:0] }
//      ch0[i] = lo & 0xFFFF;  ch1[i] = lo >> 16;
//      ch2[i] = hi & 0xFFFF;  ch3[i] = hi >> 16;
//
//    ⚠️ 为什么不用 u64 指针：BRAM 是 64 位，但 PS 的 M_AXI_GP0 是 32 位，
//       中间由 AXI Interconnect 做位宽转换 —— 一个 64 位字在 PS 眼里就是
//       相邻的两个 32 位地址。按 u32 索引（2*i、2*i+1）无论怎么转换都天然对齐。
//
//  ═══════════════════ 接进 Block Design 需要的端口（6 + 3 根线）═══════════════════
//    麦克风侧：mic_sck / mic_ws / mic_sd0..3        → 引到 J10 排针
//    BRAM 侧 ：bram_clk / bram_rst / bram_en /
//              bram_we / bram_addr / bram_din       → 接 Block Memory Generator 的 Port B
//    握手侧  ：rd_cnt_ps  ← AXI GPIO ch2（输出通道）
//              wr_cnt_ps  → AXI GPIO ch1（输入通道）
//////////////////////////////////////////////////////////////////////////////
module acq_top #(
    parameter integer FRAME = 1024       // 一帧采样点数（2 的幂）
)(
    // ---------- 时钟 ----------
    input  wire        clk_50m,      // 板载 50 MHz 晶振，引脚 U18

    // ---------- 麦克风接口（引到 J10 扩展口）----------
    output wire        mic_sck,      // 位时钟 3.125 MHz，4 个麦克风并联共用
    output wire        mic_ws,       // 帧同步 48.83 kHz，4 个麦克风并联共用
    input  wire        mic_sd0,      // 麦克风 0 数据
    input  wire        mic_sd1,      // 麦克风 1 数据
    input  wire        mic_sd2,      // 麦克风 2 数据
    input  wire        mic_sd3,      // 麦克风 3 数据

    // ---------- 与 PS 的握手（接 AXI GPIO）----------
    input  wire [1:0]  rd_cnt_ps,    // AXI GPIO ch2 的输出 → 接到这里
    output wire [1:0]  wr_cnt_ps,    // 接到 AXI GPIO ch1 的输入

    // ---------- BRAM Port B（接 Block Memory Generator）----------
    output wire        bram_clk,     // → BRAM_PORTB_CLK
    output wire        bram_rst,     // → BRAM_PORTB_RST（高有效，已取反）
    output wire        bram_en,      // → BRAM_PORTB_EN（恒 1）
    output wire        bram_we,      // → BRAM_PORTB_WE
    output wire [10:0] bram_addr,    // → BRAM_PORTB_ADDR
    output wire [63:0] bram_din      // → BRAM_PORTB_DIN
);

    //======================================================================
    // 1. 上电复位
    //    上电后先把复位按住 256 个时钟周期，等时钟稳定、麦克风内部电路
    //    也稳定了再放开，避免开头收到一段乱码。
    //    实际工程里想加手动复位的话，可以再引一个按键，两者相与即可。
    //
    //    ⚠️ rst_cnt 必须显式给初值 0：
    //       仿真中未初始化的 reg 是 x（不定态），
    //       一旦走进 "x + 1 = x" 就永远数不到 8'hFF，复位永远放不开。
    //       （真实 FPGA 上 bitstream 会把寄存器初始化成 0，所以硬件看不出问题，
    //         但仿真会挂住 —— 显式给初值让两边行为完全一致。）
    //======================================================================
    reg [7:0] rst_cnt = 8'd0;
    reg       rst_n   = 1'b0;

    always @(posedge clk_50m) begin
        if (rst_cnt == 8'hFF) begin
            rst_n <= 1'b1;                 // 数满了，放开复位
        end
        else begin
            rst_cnt <= rst_cnt + 8'd1;
            rst_n   <= 1'b0;               // 还在按住
        end
    end

    //======================================================================
    // 2. I2S 分频计数器
    //    cnt 自由运行、永不停歇。SCK 和 WS 就是它的某一位：
    //
    //      cnt[3] → 周期 2^4  = 16 拍  = 320 ns   = 3.125 MHz （SCK）
    //      cnt[9] → 周期 2^10 = 1024 拍 = 20.48 µs = 48.83 kHz（WS）
    //
    //    WS 周期 ÷ SCK 周期 = 1024 ÷ 16 = 64，
    //    正好是 I2S 一帧（左右声道各 32 位）需要的位数。
    //
    //    "让 FPGA 自己产生 SCK/WS"是一个刻意选择：
    //    这样 SCK、WS、SD 全都落在 50 MHz 这一个时钟域里，
    //    不需要引入第二个时钟、也不需要异步 FIFO。
    //======================================================================
    reg [9:0] cnt = 10'd0;

    always @(posedge clk_50m) begin
        if (!rst_n) cnt <= 10'd0;
        else        cnt <= cnt + 10'd1;
    end

    assign mic_sck = cnt[3];
    assign mic_ws  = cnt[9];

    //======================================================================
    // 3. 四个 I2S 接收，共用同一组 clk / cnt
    //======================================================================
    wire [23:0] s0, s1, s2, s3;
    wire        v0, v1, v2, v3;

    i2s_rx u_mic0 (.clk(clk_50m), .rst_n(rst_n), .cnt(cnt), .sd(mic_sd0),
                   .sample(s0), .vld(v0));
    i2s_rx u_mic1 (.clk(clk_50m), .rst_n(rst_n), .cnt(cnt), .sd(mic_sd1),
                   .sample(s1), .vld(v1));
    i2s_rx u_mic2 (.clk(clk_50m), .rst_n(rst_n), .cnt(cnt), .sd(mic_sd2),
                   .sample(s2), .vld(v2));
    i2s_rx u_mic3 (.clk(clk_50m), .rst_n(rst_n), .cnt(cnt), .sd(mic_sd3),
                   .sample(s3), .vld(v3));

    // 四路同时有效的标志。
    // 它们吃同一个 cnt，所以 v0~v3 必然在同一拍拉高，这里用"与"只是形式上的合并。
    // 用"与"而不是只看 v0 的好处：万一某路没接好，也不会静默地少一路数据。
    //（注意 vld 是纯时序产生的，只跟时钟节拍有关、跟 SD 上的数据内容无关，
    //  所以哪怕麦克风没接，vld 依然会正常产生，不会把整条链路卡住。）
    wire all_vld = v0 & v1 & v2 & v3;

    //======================================================================
    // 4. 打包 + 乒乓写控制 + 握手
    //======================================================================
    acq_to_bram #(
        .FRAME (FRAME)
    ) u_acq (
        .clk        (clk_50m),
        .rst_n      (rst_n),
        .ch0        (s0),
        .ch1        (s1),
        .ch2        (s2),
        .ch3        (s3),
        .sample_vld (all_vld),
        .rd_cnt_ps  (rd_cnt_ps),
        .wr_cnt_ps  (wr_cnt_ps),
        .bram_we    (bram_we),
        .bram_addr  (bram_addr),
        .bram_din   (bram_din)
    );

    //======================================================================
    // 5. BRAM Port B 的平台级信号
    //    Port B 用的是板上 50 MHz 晶振，而 AXI 那一侧（Port A）用的是
    //    PS 的 FCLK —— 这两个是真异步时钟域。
    //    BRAM 是真正的双口 RAM，两个端口各自独立同步，数据通路不需要打拍；
    //    唯一需要跨时钟处理的是"读完了没有"这个状态信号，
    //    那部分在 acq_to_bram 里用两拍同步器做掉了。
    //======================================================================
    assign bram_clk = clk_50m;      // Port B 时钟 = 50 MHz 晶振
    assign bram_rst = ~rst_n;       // BMG 的复位是高有效，这里取反
    assign bram_en  = 1'b1;         // Port B 常开（只写不读，无需动态门控）

endmodule
