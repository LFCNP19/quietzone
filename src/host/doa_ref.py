#!/usr/bin/env python3
"""doa_ref.py - doa_angle 的独立参考值发生器（047 轮）

用途：用双精度 atan2 算出 tb_doa_angle 每条用例的**期望角度**，
     把结果贴进 tb 的用例表。RTL 里是 CORDIC 定点迭代，参考值走的是
     完全不同的算法（双精度反三角函数），这样"两边都对"才有说服力。

用法：
    python python/doa_ref.py            # 打印用例表（SV 片段）
    python python/doa_ref.py --check    # 只打印统计

口径（与 rtl/doa_angle.v 文件头一致）：
    角度 = degrees(atan2(delay_y, delay_x)) % 360
    两个实参顺序固定为 (dy, dx)，+X 轴为 0 度，逆时针为正。
    两个时延都为 0 -> 方向不可分辨 -> 期望 valid = 0（角度任意）。
"""
import math
import sys

Q = 256  # Q8.8：1 个采样点 = 256 LSB


def q(v):
    return int(round(v * Q))


# (delay_x, delay_y, i_valid, note)；时延单位 = 采样点
CASES = [
    (0.0, 0.0, 1, "all zero -> no direction"),
    (8.54, 0.0, 1, "+X axis: source nearest mic2"),
    (-8.54, 0.0, 1, "-X axis"),
    (0.0, 8.54, 1, "+Y axis: source nearest mic4"),
    (0.0, -8.54, 1, "-Y axis"),
    (5.859375, 5.859375, 1, "diag +45"),
    (-5.859375, 5.859375, 1, "diag +135"),
    (-5.859375, -5.859375, 1, "diag +225"),
    (5.859375, -5.859375, 1, "diag +315"),
    (8.5, 0.5, 1, "small angle 3.37 deg"),
    (6.25, 3.75, 1, "atan(0.6) = 30.96 deg"),
    (0.390625, 8.5390625, 1, "near +Y, dx tiny"),
    (-0.390625, 8.5390625, 1, "near +Y, dx tiny negative"),
    (8.5390625, -0.390625, 1, "just below +X (357 deg)"),
    (1.0, 1.0, 1, "unit vector 45 deg"),
    (-1.0, -1.0, 1, "unit vector 225 deg"),
    (12.0, 4.0, 1, "window edge, 18.43 deg"),
    (4.0, 12.0, 1, "window edge, 71.57 deg"),
    (-12.0, 4.0, 1, "window edge, 161.57 deg"),
    (-4.0, -12.0, 1, "window edge, 251.57 deg"),
    (1.0 / Q, 1.0 / Q, 1, "1 LSB both axes"),
    (1.0, 0.0, 1, "exactly +X"),
    (0.0, 11.71875, 1, "exactly +Y (window edge)"),
    (-5.859375, 1.5625, 1, "quadrant II, 165.07 deg"),
    (4.8203125, -9.16015625, 1, "quadrant IV, 297.75 deg"),
    (3.0, 3.0, 0, "i_valid=0 -> must be invalid"),
]


def angle_of(dx, dy):
    return math.degrees(math.atan2(dy, dx)) % 360.0


def main():
    rows = []
    for dx, dy, v, note in CASES:
        a = angle_of(dx, dy)
        exp = int(math.floor(a + 0.5)) % 360
        valid = 1 if (v and (dx != 0.0 or dy != 0.0)) else 0
        rows.append((q(dx), q(dy), v, exp % 360, valid, note))
    if "--check" in sys.argv:
        for r in rows:
            print(r)
        return
    print("    // {dx_q8_8, dy_q8_8, i_valid, exp_angle, exp_valid}  -- generated by python/doa_ref.py")
    for dxq, dyq, v, exp, valid, note in rows:
        print(f"    {{16'sd{dxq:6d}, 16'sd{dyq:6d}, 1'b{v}, 9'd{exp:3d}, 1'b{valid}}},  // {note}")
    print(f"    // total cases = {len(rows)}")


if __name__ == "__main__":
    main()
